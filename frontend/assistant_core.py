def explain(client, facts, kind="single", model=None, max_tokens=2000):
    """Plain-language text from the given facts; retried once if the reply comes back empty."""
    text = ""
    for _ in range(2):
        response = client.messages.create(model=model or CLAUDE_MODEL, max_tokens=max_tokens,
                                          system=EXPLAIN_PROMPT if kind == "single" else PLAN_PROMPT,
                                          messages=[{"role": "user", "content": json.dumps(facts)}])
        text = text_of(response.content)
        if text:
            break
    if not text:
        return {"answer": "", "untraced": [], "empty": True}
    return {"answer": text, "untraced": untraced_numbers(text, [facts]), "empty": False}


