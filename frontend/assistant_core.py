def backend_post(path, payload):
    """Call a backend endpoint; errors come back as {"error": ...} so the assistant can explain them."""
    try:
        response = requests.post(f"{BACKEND_URL}{path}", json=payload, timeout=90)
    except requests.exceptions.RequestException as error:
        return {"error": f"The SuperKart service could not be reached ({error}). It may be waking up - try again in a minute."}
    try:
        return response.json()
    except ValueError:
        return {"error": f"The SuperKart service returned HTTP {response.status_code}."}


def tool_get_outlets():
    """Outlet profiles from the historical data - no model accuracy here (see get_model_accuracy)."""
    return {"source": HISTORICAL,
            "outlets": {s: {"store_type": v["Store_Type"], "size": v["Store_Size"],
                            "city_tier": v["Store_Location_City_Type"], "opened": v["Established"],
                            "average_revenue_per_product": v["avg"],
                            "8_in_10_products_earned_between": [v["p10"], v["p90"]],
                            "mrp_range_sold": v["mrp"], "weight_range_sold": v["weight"]} for s, v in STORES.items()},
            "tip": "For products, revenue and categories per outlet use summarise_data."}


def tool_get_model_accuracy():
    return {"measured_on": f"{REFERENCE['overall']['test_rows']} products the model never saw (test set)",
            "per_outlet": {s: {"average_error_pct": round(100 * v["mape"], 1),
                               "error_9_in_10_products_within_pct": round(100 * v["err90"], 1),
                               "test_products": v["test_rows"]} for s, v in STORES.items()},
            "all_outlets": {"model_average_error_pct": round(100 * REFERENCE["overall"]["model_mape"], 1),
                            "store_average_rule_error_pct": round(100 * REFERENCE["overall"]["store_average_mape"], 1)}}


def tool_get_category_ranges(product_type, outlet=None):
    """MRP and weight range of the products SuperKart sold in a category - overall, or at one outlet."""
    if product_type not in TYPE_RANGES:
        return {"error": f"Unknown product category '{product_type}'.", "valid_categories": PRODUCT_TYPES}
    r = TYPE_RANGES[product_type]
    area = TRAINED_RANGES["Product_Allocated_Area"]
    result = {"product_type": product_type, "source": HISTORICAL,
              "all_outlets": {"mrp_range_sold": r["mrp"], "weight_range_sold": r["weight"]},
              "sugar_options": sugar_options(product_type),
              "display_share_pct_range": [round(100 * area[0], 1), round(100 * area[1], 1)],
              "default_display_share_pct": round(100 * DEFAULTS["display_share_median"], 1),
              "perishable": product_type in PERISHABLES,
              "note": "Weight is in the unit of the source data. The model can only forecast within the ranges sold."}
    if outlet:
        ranges = {}
        for measure in ("mrp", "weight"):
            answer = backend_post("/v1/data/summary", {"measure": measure, "stats": ["min", "max"],
                                                       "filters": {"outlet": outlet, "product_type": product_type}})
            if "error" in answer:
                return answer
            row = answer["rows"][0] if answer["rows"] else {}
            ranges[f"{measure}_range_sold"] = [row.get("min"), row.get("max")]
            ranges["products"] = answer.get("products", 0)
        result[f"at_{outlet}"] = ranges
    return result


def tool_summarise_data(group_by=None, measure="revenue", stats=None, filters=None):
    return backend_post("/v1/data/summary", {"group_by": group_by or [], "measure": measure,
                                             "stats": stats or ["sum", "mean"], "filters": filters or {}})


def tool_data_relationship(x, y, group_by=None, filters=None):
    return backend_post("/v1/data/relationship", {"x": x, "y": y, "group_by": group_by, "filters": filters or {}})


def tool_forecast_product(outlet, product_type, mrp, weight, sugar_content=None, display_share_pct=None):
    """Validate in code, call the deployed model, add the planning facts."""
    outlet = str(outlet).strip().upper()
    if outlet not in STORES:
        return {"error": f"'{outlet}' is not a SuperKart outlet. Only {', '.join(STORES)} exist in the data."}
    if product_type not in TYPE_RANGES:
        return {"error": f"Unknown product category '{product_type}'.", "valid_categories": PRODUCT_TYPES}
    limits = TYPE_RANGES[product_type]
    problems = []
    if not limits["mrp"][0] <= float(mrp) <= limits["mrp"][1]:
        problems.append(f"MRP {mrp} is outside the MRP range of {product_type} products sold ({limits['mrp'][0]}-{limits['mrp'][1]})")
    if not limits["weight"][0] <= float(weight) <= limits["weight"][1]:
        problems.append(f"weight {weight} is outside the weight range of {product_type} products sold "
                        f"({limits['weight'][0]}-{limits['weight'][1]})")
    assumed = []
    if sugar_content is None:
        sugar_content = sugar_options(product_type)[0]
        assumed.append(f"sugar content '{sugar_content}' (most common for {product_type})")
    elif sugar_content not in sugar_options(product_type):
        problems.append(f"sugar content must be one of {sugar_options(product_type)} for {product_type}")
    if display_share_pct is None:
        display_share_pct = round(100 * DEFAULTS["display_share_median"], 1)
        assumed.append(f"display share {display_share_pct}% (median in the data)")
    area_low, area_high = (100 * v for v in TRAINED_RANGES["Product_Allocated_Area"])
    if not area_low <= float(display_share_pct) <= area_high:
        problems.append(f"display share must be between {area_low:.1f}% and {area_high:.1f}%")
    if problems:
        return {"error": "Not forecast: " + "; ".join(problems) + ". The model has no data outside these ranges."}

    row = model_row(outlet, product_type, sugar_content, weight, mrp, float(display_share_pct) / 100)
    try:
        forecast = predict(row)
    except requests.exceptions.RequestException as error:
        return {"error": f"The forecasting service could not be reached ({error}). It may be waking up - try again in a minute."}
    store = STORES[outlet]
    outside_outlet = [n for n, v, rng in [("MRP", float(mrp), store["mrp"]), ("weight", float(weight), store["weight"])]
                      if not rng[0] <= v <= rng[1]]
    return {"inputs_used": {"outlet": outlet, "product_type": product_type, "mrp": float(mrp), "weight": float(weight),
                            "sugar_content": sugar_content, "display_share_pct": float(display_share_pct)},
            "assumed_inputs": assumed,
            "outside_outlet_range": (f"The {' and '.join(outside_outlet)} is within the range for {product_type} but "
                                     f"outside what {outlet} sells - less reliable.") if outside_outlet else None,
            **planning_facts(outlet, product_type, float(mrp), forecast)}


