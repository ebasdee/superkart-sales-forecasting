def outlet_position(store_id, value):
    """Share (%) of the outlet's products whose actual revenue is below this value (historical data)."""
    pct = OUTLET_DIST[store_id]["pct"]
    if value <= pct[0]:
        return 0.0
    if value >= pct[-1]:
        return 100.0
    for i in range(1, len(pct)):
        if value <= pct[i]:
            low, high = pct[i - 1], pct[i]
            fraction = 0 if high == low else (value - low) / (high - low)
            return 5 * (i - 1 + fraction)
    return 100.0


def tier_of(store_id, value):
    d = OUTLET_DIST[store_id]
    if value >= d["p80"]:
        return "Top 20%"
    if value < d["p20"]:
        return "Bottom 20%"
    return "Middle 60%"


def stock_range(store_id, forecast, mrp):
    error = STORES[store_id]["err90"]
    units = forecast / mrp
    return units, units * (1 - error), units * (1 + error)


def product_family(product_type):
    return "DR" if product_type in DRINKS else "NC" if product_type in NON_CONSUMABLES else "FD"


def sugar_options(product_type):
    return ["No Sugar"] if product_type in NON_CONSUMABLES else ["Low Sugar", "Regular"]


def model_row(store_id, product_type, sugar, weight, mrp, area_share):
    store = STORES[store_id]
    return {"Product_Weight": float(weight), "Product_Sugar_Content": sugar,
            "Product_Allocated_Area": float(area_share), "Product_MRP": float(mrp),
            "Store_Size": store["Store_Size"], "Store_Location_City_Type": store["Store_Location_City_Type"],
            "Store_Type": store["Store_Type"], "Product_Id_char": product_family(product_type),
            "Store_Age_Years": REFERENCE_YEAR - store["Established"],
            "Product_Type_Category": "Perishables" if product_type in PERISHABLES else "Non Perishables"}


def predict(row):
    response = requests.post(f"{BACKEND_URL}/v1/predict", json=row, timeout=90)
    response.raise_for_status()
    return float(response.json()["Sales"])


def planning_facts(store_id, product_type, mrp, forecast):
    """Everything the app shows next to a forecast: tier, position, stock range and expected accuracy."""
    store = STORES[store_id]
    units, low, high = stock_range(store_id, forecast, mrp)
    return {
        "forecast_revenue": round(forecast, 2),
        "forecast_period": "same period as the historical sales data (the data has no dates)",
        "tier_at_outlet": tier_of(store_id, forecast),
        "higher_than_pct_of_outlet_products": round(outlet_position(store_id, forecast)),
        "vs_outlet_average_pct": round(100 * (forecast / store["avg"] - 1), 1),
        "outlet_average_revenue_per_product": store["avg"],
        "suggested_stock_units": round(units),
        "stock_range_units": [round(low), round(high)],
        "stock_range_basis_pct": round(100 * store["err90"], 1),
        "outlet_average_error_pct": round(100 * store["mape"], 1),
        "perishable": product_type in PERISHABLES,
        "stocking_note": ("Perishable - stock near the middle of the range." if product_type in PERISHABLES
                          else "Long-life product - the upper end of the range is lower risk."),
        "low_accuracy_warning": (f"Lower accuracy at {store_id} (average error about {100 * store['mape']:.0f}%): "
                                 "keep a safety margin and review the order by hand.") if store["mape"] > 0.10 else None,
    }


